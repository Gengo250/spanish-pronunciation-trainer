"""Content validation.

It exists because language material arrives from everywhere -- written by hand,
imported from a spreadsheet, generated by an LLM -- and wrong content teaches
wrong. The project rule is explicit: **do not assume a model-generated
translation or grammar note is correct**. Here we check what can be checked
mechanically; the rest becomes a warning for human review.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field

from ..assessment.accents import equivalent
from ..assessment.g2p import G2PError, phonemize_text
from .models import Deck, Flashcard, Level

# Expected length ranges per level, in words. Generous bounds: they are there to
# catch a card at the wrong level, not to straitjacket the content.
LEVEL_WORD_RANGES: dict[Level, tuple[int, int]] = {
    Level.BEGINNER: (1, 6),
    Level.INTERMEDIATE: (2, 14),
    Level.ADVANCED: (3, 30),
}

# Everything that can legitimately appear in written Spanish. Anything outside
# it is a typo or text from another language that slipped in -- which really does
# happen with spreadsheet imports and generated content.
ALLOWED_CHARS = set(
    "abcdefghijklmnopqrstuvwxyz"
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "áéíóúüñÁÉÍÓÚÜÑ"
    "0123456789"
    " .,;:!?¿¡'\"()-–—…«»/%"
)


@dataclass
class Issue:
    card_id: str
    field_name: str
    message: str
    severity: str = "warning"


@dataclass
class ValidationReport:
    issues: list[Issue] = field(default_factory=list)
    checked: int = 0

    @property
    def errors(self) -> list[Issue]:
        return [i for i in self.issues if i.severity == "error"]

    @property
    def warnings(self) -> list[Issue]:
        return [i for i in self.issues if i.severity == "warning"]

    @property
    def ok(self) -> bool:
        return not self.errors

    def add(self, card_id: str, field_name: str, message: str, severity: str = "warning"):
        self.issues.append(Issue(card_id, field_name, message, severity))


def validate_deck(deck: Deck, *, check_phonemes: bool = True) -> ValidationReport:
    report = ValidationReport(checked=len(deck.cards))

    # 1. Repeated ids break the learner's progress: they would review the wrong card.
    for card_id, count in Counter(c.id for c in deck.cards).items():
        if count > 1:
            report.add(card_id, "id", f"id repeated {count} times", "error")

    # 2. Repeated text under different ids is nearly always a duplicated import.
    for text, count in Counter(c.text.strip().lower() for c in deck.cards).items():
        if count > 1:
            report.add(text[:32], "text", f"text repeated across {count} cards")

    for card in deck.cards:
        _validate_card(card, report, check_phonemes=check_phonemes)
    return report


def _validate_card(card: Flashcard, report: ValidationReport, *, check_phonemes: bool):
    low, high = LEVEL_WORD_RANGES[card.level]
    if not low <= card.word_count <= high:
        report.add(
            card.id, "level",
            f"level {card.level.value} expects {low}-{high} words, the card has "
            f"{card.word_count}",
        )

    # Spanish and Portuguese share many cognates ("azul", "verde", "carro"), so
    # an identical translation is suspicious, not an error.
    if card.text == card.translation:
        report.add(
            card.id, "translation",
            "translation identical to the original text -- confirm it really is a cognate",
        )

    unexpected = sorted({c for c in card.text if c not in ALLOWED_CHARS})
    if unexpected:
        report.add(
            card.id, "text",
            f"character outside the Spanish alphabet: {' '.join(repr(c) for c in unexpected)}",
            "error",
        )

    if card.card_type.value == "question" and not card.text.strip().endswith("?"):
        report.add(card.id, "text", "question-type card without a final '?'")

    if card.text.strip().startswith("¿") and not card.text.strip().endswith("?"):
        report.add(card.id, "text", "opens '¿' but does not close '?'", "error")

    if card.text.strip().endswith("?") and not card.text.strip().startswith("¿"):
        report.add(card.id, "text", "a Spanish question must open with '¿'")

    # 3. The G2P is the strongest mechanical check we have: if espeak-ng cannot
    #    phonemize it, the text is almost certainly not valid Spanish.
    if check_phonemes:
        try:
            words = phonemize_text(card.text)
        except G2PError as exc:  # pragma: no cover - depende do espeak
            report.add(card.id, "text", f"espeak-ng failed: {exc}")
        else:
            if not words:
                report.add(card.id, "text", "no phoneme generated for the text", "error")
            # The comparison goes through the equivalence classes because the G2P
            # runs word by word and misses allophony across words: "dias" alone
            # gives /d/, but in "buenos dias" the same letter sounds /ð/. Demanding
            # the exact symbol would flag an error on a correct card.
            produced = {p for w in words for p in w.phonemes}
            for target in card.phoneme_targets:
                if not any(equivalent(target, p) for p in produced):
                    report.add(
                        card.id, "phoneme_targets",
                        f"target /{target}/ does not appear in the pronunciation of {card.text!r}",
                    )


def fill_expected_phonemes(deck: Deck, voice: str = "es-419") -> Deck:
    """Fills `expected_phonemes` using espeak-ng (never an LLM)."""
    for card in deck.cards:
        words = phonemize_text(card.text, voice)
        card.expected_phonemes = [p for w in words for p in w.phonemes]
    return deck
